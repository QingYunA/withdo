#!/usr/bin/env python3
"""Turn the harness marks of the v14 mockup into pixel sprites for the Settings rows.

The mockup (docs/design/mockups/v14.html) embeds every official harness mark as four small PNGs
in its ICONS object: 24 x 24 for the "On this Mac" rows, 18 x 18 for "More", each with a dark
variant. The marks are the official lobe-icons / Iconify drawings, rasterised in the mockup; the
PNGs carry the anti-aliasing of that raster, which the Pixel language does not allow.

This tool reads the mockup itself (the committed source of the approved shapes), keeps a pixel
where the mark covers at least half of it, quantises the lit pixels of each sprite to at most 24
colours, and writes app/theme/harness_marks.go. One rune stands for one colour. Claude Code is not
written: it keeps the app's own 12 x 12 crab (theme.spriteClaude).

Needs Pillow. Run from the repository root:

    python3 docs/design/tools/harness_marks.py
"""
import base64
import io
import os
import re

from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
MOCKUP = os.path.join(ROOT, "docs", "design", "mockups", "v14.html")
OUT = os.path.join(ROOT, "app", "theme", "harness_marks.go")

# agentsetup id -> the key of the mark in the mockup's ICONS. Claude Code is the app's crab.
MARKS = [
    ("codex", "codex"),
    ("deepseek", "deepseek"),
    ("gemini", "gemini"),
    ("cursor", "cursor"),
    ("opencode", "opencode"),
    ("copilot", "githubcopilot"),
    ("qwen", "qwen"),
    ("kimi", "kimi"),
    ("windsurf", "windsurf"),
    ("zed", "zed"),
    ("amp", "amp"),
    ("kiro", "kiro"),
    ("cline", "cline"),
]

# a pixel is part of the mark when the raster covers at least half of it
COVER = 128
# at most this many colours per sprite; the Pixel language wants a small flat palette
MAX_COLORS = 24
RUNES = "abcdefghijklmnopqrstuvwxyz"


def read_icons():
    """The mark key -> {variant: base64 PNG} of the mockup's ICONS object."""
    html = open(MOCKUP, encoding="utf-8").read()
    icons = {}
    current = None
    for line in html[html.index("const ICONS = {"):html.index("const ICON_ALIAS")].splitlines():
        mark = re.match(r"\s+(\w+): \{", line)
        if mark:
            current = mark.group(1)
            icons[current] = {}
            continue
        variant = re.match(r"\s+(dark24|dark18|24|18): 'data:image/png;base64,([^']+)'", line)
        if variant and current:
            icons[current][variant.group(1)] = variant.group(2)
    return icons


def sprite(png_b64):
    """One PNG as (rows, palette): a rune a colour, '.' transparent, at most MAX_COLORS runes."""
    im = Image.open(io.BytesIO(base64.b64decode(png_b64))).convert("RGBA")
    w, h = im.size
    px = im.load()
    cells, lit = [], []
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = px[x, y]
            if a >= COVER:
                row.append((r, g, b))
                lit.append((r, g, b))
            else:
                row.append(None)
        cells.append(row)
    if not lit:
        raise SystemExit("a mark is empty")
    strip = Image.new("RGB", (len(lit), 1))
    strip.putdata(lit)
    q = strip.quantize(colors=min(MAX_COLORS, len(RUNES)), method=Image.Quantize.MEDIANCUT)
    pal, rows, index = {}, [], iter(q.getdata())
    flat = q.getpalette()
    for cell_row in cells:
        out = []
        for cell in cell_row:
            if cell is None:
                out.append(".")
                continue
            i = next(index)
            pal[RUNES[i]] = "#%02X%02X%02X" % tuple(flat[i * 3:i * 3 + 3])
            out.append(RUNES[i])
        rows.append("".join(out))
    return rows, pal


def emit(name, comment, sprites):
    out = ["// " + comment, "var " + name + " = map[string]*Sprite{"]
    for agent_id, (rows, pal) in sprites:
        spec = " ".join(rune + pal[rune] for rune in sorted(pal))
        out.append('\t"%s": {Palette: pal("%s"), Rows: []string{' % (agent_id, spec))
        out += ['\t\t"%s",' % row for row in rows]
        out.append("\t}},")
    out.append("}")
    return out


def main():
    icons = read_icons()
    light24, dark24, light18, dark18 = [], [], [], []
    for agent_id, key in MARKS:
        variants = icons[key]
        light24.append((agent_id, sprite(variants["24"])))
        dark24.append((agent_id, sprite(variants["dark24"])))
        light18.append((agent_id, sprite(variants["18"])))
        dark18.append((agent_id, sprite(variants["dark18"])))
    go = [
        "// Code generated by docs/design/tools/harness_marks.py from docs/design/mockups/v14.html; DO NOT EDIT.",
        "",
        "package theme",
        "",
        "// The harness marks are the official lobe-icons / Iconify drawings of the coding agents, taken",
        "// from the pixel PNGs the v14 mockup embeds (ICONS) and quantised to at most 24 colours. The",
        "// 24 x 24 sprites are for the rows of On this Mac, the 18 x 18 ones for More; each dark set is",
        "// the mockup's dark variant of its light set. Claude Code is not here: it is the app's own",
        "// 12 x 12 crab, spriteClaude.",
    ]
    go += emit("harnessMarks24", "harnessMarks24 are the official marks at 24 x 24: On this Mac.", light24)
    go.append("")
    go += emit("harnessMarks24Dark", "harnessMarks24Dark are the same marks as the mockup draws them on a dark window.", dark24)
    go.append("")
    go += emit("harnessMarks18", "harnessMarks18 are the official marks at 18 x 18: More.", light18)
    go.append("")
    go += emit("harnessMarks18Dark", "harnessMarks18Dark are the same small marks in their dark variants.", dark18)
    open(OUT, "w", encoding="utf-8").write("\n".join(go) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
