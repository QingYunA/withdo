#!/usr/bin/env python3
"""Sample the providers' official marks onto the 18 x 18 pixel grid of the Pixel language.

Each SVG in app/theme/logos is rendered at 288 px by headless Chrome, then cut into 18 x 18 cells
of 16 px. A cell is lit when the mark covers enough of it, in the average color of what covers it:
flat marks are snapped to their one official color, gradient marks are reduced to a small palette,
and one-color marks (drawn in the text color) use the rune 'k'. The result is written to
app/theme/provider_marks.go (and, for the v11 draft, to docs/design/mockups/v11-marks.json).

Needs Google Chrome and Pillow. Run from the repository root:

    python3 docs/design/tools/sample_marks.py
"""
import json
import os
import subprocess
import tempfile

from PIL import Image

CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
GRID, SIZE = 18, 288
CELL = SIZE // GRID

# preset id -> (file in app/theme/logos, kind, its color for a flat mark)
MARKS = {
    "openai": ("openai", "one", None),
    "deepseek": ("deepseek-color", "flat", "#4D6BFE"),
    "kimi": ("kimi", "one", None),
    "zhipu": ("zhipu-color", "flat", "#3859FF"),
    "qwen": ("qwen-color", "gradient", None),
    "gemini": ("gemini-color", "gradient", None),
    "openrouter": ("openrouter-color", "flat", "#C8FF00"),
    "siliconflow": ("siliconcloud-color", "flat", "#6E29F6"),
    "ollama": ("ollama", "one", None),
}
# how much of a cell the mark must cover to light it; Qwen's faces are cut out, so its thin
# sides need a lower bar to survive
COVER = {"qwen": 0.35}
RUNES = "abcdefghijlmnopqrstuvwxyzABCDEFGHIJLMNOPQRSTUVWXYZ"  # no 'k', which is the text color


def render(svg_path, out_png):
    svg = open(svg_path).read().replace("currentColor", "#000000").replace("<svg", f'<svg width="{SIZE}" height="{SIZE}"', 1)
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False) as f:
        f.write(f'<html><body style="margin:0;background:transparent">{svg}</body></html>')
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                    "--default-background-color=00000000", f"--window-size={SIZE},{SIZE}",
                    f"--screenshot={out_png}", "file://" + f.name], check=True, capture_output=True)
    os.unlink(f.name)


def sample(png, cover):
    im = Image.open(png).convert("RGBA")
    px = im.load()
    cells = []
    for y in range(GRID):
        row = []
        for x in range(GRID):
            n = on = r = g = b = 0
            for yy in range(y * CELL, (y + 1) * CELL):
                for xx in range(x * CELL, (x + 1) * CELL):
                    pr, pg, pb, pa = px[xx, yy]
                    n += 1
                    if pa >= 100:
                        on += 1
                        r, g, b = r + pr, g + pg, b + pb
            row.append((r // on, g // on, b // on) if on / n >= cover else None)
        cells.append(row)
    return cells


def palette_of(cells, kind, flat):
    """Rows of runes and the palette they index."""
    if kind == "one":
        return [["k" if c else "." for c in row] for row in cells], {"k": "#1D1D1F"}
    if kind == "flat":
        return [["a" if c else "." for c in row] for row in cells], {"a": flat}
    lit = [c for row in cells for c in row if c]
    strip = Image.new("RGB", (len(lit), 1))
    strip.putdata(lit)
    q = strip.quantize(colors=min(24, len(RUNES)), method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    idx = iter(q.getdata())
    rows, used = [], {}
    for row in cells:
        out = []
        for c in row:
            if not c:
                out.append(".")
                continue
            i = next(idx)
            used[RUNES[i]] = "#%02X%02X%02X" % tuple(pal[i * 3:i * 3 + 3])
            out.append(RUNES[i])
        rows.append(out)
    return rows, used


def main():
    tmp = tempfile.mkdtemp()
    go = ["// Code generated by docs/design/tools/sample_marks.py from app/theme/logos; DO NOT EDIT.", "",
          "package theme", "",
          "// providerMarks are the providers' official marks sampled onto an 18 x 18 grid (see Pixel",
          "// language in docs/design/ui-spec.md). A one-color mark uses the rune 'k', drawn in the text color.",
          "var providerMarks = map[string]*Sprite{"]
    draft = {}
    for pid, (name, kind, flat) in MARKS.items():
        png = os.path.join(tmp, pid + ".png")
        render(os.path.join("app/theme/logos", name + ".svg"), png)
        rows, pal = palette_of(sample(png, COVER.get(pid, 0.45)), kind, flat)
        spec = " ".join(f"{k}{v}" for k, v in sorted(pal.items()))
        go.append(f'\t"{pid}": {{Palette: pal("{spec}"), Rows: []string{{')
        go += [f'\t\t"{"".join(r)}",' for r in rows]
        go.append("\t}},")
        draft[pid] = {"rows": ["".join(r) for r in rows], "pal": pal, "one": kind == "one"}
    go += ["}", "", "// oneColorMarks are the marks drawn in the text color, so they turn white in dark mode.",
           "var oneColorMarks = map[string]bool{" + ", ".join(f'"{p}": true' for p, m in MARKS.items() if m[1] == "one") + "}", ""]
    open("app/theme/provider_marks.go", "w").write("\n".join(go))
    json.dump(draft, open("docs/design/mockups/v11-marks.json", "w"), ensure_ascii=False)


if __name__ == "__main__":
    main()
