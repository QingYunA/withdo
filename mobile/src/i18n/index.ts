export type MessageKey = keyof typeof en;
export function resolveLocale(language: Language): 'zh' | 'en' {
  if (language !== 'system') return language;
  return getLocales()[0].languageCode === 'zh' ? 'zh' : 'en';
}
export function translator(language: Language) {
  const locale = resolveLocale(language);
  return {
    locale,
    t: (key: MessageKey): string => (locale === 'zh' ? zh : en)[key],
  };
}
export function statusKey(status: TaskStatus): MessageKey {
  return `status_${status}`;
}
export function dateLabel(
  iso: string,
  locale: string,
  withTime = false,
): string {
  const date = new Date(iso);
  if (!Number.isFinite(date.getTime())) return '';
  return new Intl.DateTimeFormat(locale, {
    month: 'short',
    day: 'numeric',
    ...(withTime ? ({ hour: 'numeric', minute: '2-digit' } as const) : {}),
  }).format(date);
}
export function dayKey(value: string | Date): string {
  const d = typeof value === 'string' ? new Date(value) : value;
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}
