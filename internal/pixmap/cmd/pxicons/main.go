// Command pxicons turns a directory of pixelarticons SVGs into app/theme/category_icons_gen.go: the
// 12 x 12 bitmaps a category can pick as its icon. Run it through scripts/category-icons.sh, which
// fetches the pinned release.
//
//	pxicons -svg DIR -curated docs/design/category-icons.txt -max-error 16 -o app/theme/category_icons_gen.go
//
// Every icon that is not a "-sharp" variant and reduces with at most -max-error wrong cells (of 576)
// goes into the table; the rest are listed on stderr as dropped. The curated file names the icons the
// picker shows first, in groups, with Chinese keywords; a curated icon either converts or carries a
// hand-drawn 12-row override in the file, and the run fails otherwise.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/QingYunA/adhd-todo/internal/pixmap"
)

func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "pxicons:", err)
		os.Exit(1)
	}
}

// icon is one row of the table.
type icon struct {
	name, hex, keywords string
	err                 int
}

func run(args []string, log io.Writer) error {
	fs := flag.NewFlagSet("pxicons", flag.ContinueOnError)
	fs.SetOutput(log)
	svgDir := fs.String("svg", "", "directory of pixelarticons SVG files")
	curatedPath := fs.String("curated", "", "curated icon list (docs/design/category-icons.txt)")
	maxErr := fs.Int("max-error", 16, "most wrong 24 x 24 cells an icon may have and still be kept")
	source := fs.String("source", "pixelarticons", "library name and version for the file header")
	outPath := fs.String("o", "", "output Go file (default stdout)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *svgDir == "" || *curatedPath == "" {
		return fmt.Errorf("-svg and -curated are required")
	}
	f, err := os.Open(*curatedPath)
	if err != nil {
		return err
	}
	groups, err := parseCurated(f)
	f.Close()
	if err != nil {
		return fmt.Errorf("%s: %w", *curatedPath, err)
	}
	curated := map[string]curatedIcon{}
	for _, g := range groups {
		for _, c := range g.Icons {
			curated[c.Name] = c
		}
	}

	files, err := filepath.Glob(filepath.Join(*svgDir, "*.svg"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no SVG files in %s", *svgDir)
	}
	sort.Strings(files)
	table := map[string]icon{}
	lossless, sharp := 0, 0
	var problems []string
	for _, file := range files {
		name := strings.TrimSuffix(filepath.Base(file), ".svg")
		if strings.HasSuffix(name, "-sharp") {
			sharp++
			continue
		}
		c, hasCurated := curated[name]
		if hasCurated && c.Rows != nil {
			continue // drawn by hand
		}
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		b, errCells, err := pixmap.FromRectSVG(data)
		switch {
		case err != nil:
			fmt.Fprintf(log, "dropped %s: %v\n", name, err)
		case b.Empty():
			fmt.Fprintf(log, "dropped %s: nothing is left\n", name)
		case errCells > *maxErr:
			fmt.Fprintf(log, "dropped %s %d\n", name, errCells)
		default:
			if errCells == 0 {
				lossless++
			}
			table[name] = icon{name: name, hex: b.Hex(), keywords: c.Keywords, err: errCells}
			continue
		}
		if hasCurated {
			problems = append(problems, name)
		}
	}
	for _, g := range groups {
		for _, c := range g.Icons {
			if c.Rows != nil {
				b, err := pixmap.ParseRows(c.Rows)
				if err != nil {
					return fmt.Errorf("%s: %w", c.Name, err)
				}
				table[c.Name] = icon{name: c.Name, hex: b.Hex(), keywords: c.Keywords}
			} else if _, ok := table[c.Name]; !ok && !contains(problems, c.Name) {
				problems = append(problems, c.Name+" (no such icon)")
			}
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("curated icons that do not convert; draw them by hand in the list or pick others: %s", strings.Join(problems, ", "))
	}
	fmt.Fprintf(log, "kept %d icons (%d lossless, error at most %d), skipped %d sharp variants\n", len(table), lossless, *maxErr, sharp)

	out := io.Writer(os.Stdout)
	if *outPath != "" {
		file, err := os.Create(*outPath)
		if err != nil {
			return err
		}
		defer file.Close()
		out = file
	}
	return generate(out, *source, table, groups)
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// generate writes the Go file: the table sorted by name, then the curated groups by name.
func generate(w io.Writer, source string, table map[string]icon, groups []curatedGroup) error {
	names := make([]string, 0, len(table))
	for n := range table {
		names = append(names, n)
	}
	sort.Strings(names)
	bw := bufio.NewWriter(w)
	fmt.Fprintf(bw, "// Code generated by scripts/category-icons.sh (internal/pixmap/cmd/pxicons); DO NOT EDIT.\n\n")
	fmt.Fprintf(bw, "package theme\n\n")
	fmt.Fprintf(bw, "// categoryIconData holds the icons of %s (MIT, see pixel-icons/LICENSE) that reduce to a\n", source)
	fmt.Fprintf(bw, "// 12 x 12 grid with little loss, plus the hand-drawn ones of docs/design/category-icons.txt.\n")
	fmt.Fprintf(bw, "// Each row is a name, the bitmap as 36 hex digits and the Chinese keywords the search also reads.\n")
	fmt.Fprintf(bw, "var categoryIconData = []categoryIconRow{\n")
	for _, n := range names {
		ic := table[n]
		fmt.Fprintf(bw, "\t{%q, %q, %q},\n", ic.name, ic.hex, ic.keywords)
	}
	fmt.Fprintf(bw, "}\n\n")
	fmt.Fprintf(bw, "// categoryIconGroupData is the curated list the picker shows before anything is typed.\n")
	fmt.Fprintf(bw, "var categoryIconGroupData = []categoryIconGroupRow{\n")
	for _, g := range groups {
		fmt.Fprintf(bw, "\t{%q, []string{", g.Name)
		for i, c := range g.Icons {
			if i > 0 {
				fmt.Fprint(bw, ", ")
			}
			fmt.Fprintf(bw, "%q", c.Name)
		}
		fmt.Fprintf(bw, "}},\n")
	}
	fmt.Fprintf(bw, "}\n")
	return bw.Flush()
}

type curatedIcon struct {
	Name     string
	Keywords string
	Rows     []string // a hand-drawn bitmap, 12 rows of 12 characters; nil to convert the library's
}

type curatedGroup struct {
	Name  string
	Icons []curatedIcon
}

var rowRe = regexp.MustCompile(`^[.#]+$`)

// parseCurated reads the curated list: "# comment" lines, "[Group]" headers, "name keyword ..." lines
// and, under a name, 12 indented rows of "." and "#" that replace the library's drawing.
func parseCurated(r io.Reader) ([]curatedGroup, error) {
	var groups []curatedGroup
	seen := map[string]bool{}
	sc := bufio.NewScanner(r)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(line, "["):
			if !strings.HasSuffix(line, "]") || len(line) < 3 {
				return nil, fmt.Errorf("line %d: a group header looks like [Work]", n)
			}
			groups = append(groups, curatedGroup{Name: line[1 : len(line)-1]})
		case rowRe.MatchString(line) && strings.HasPrefix(sc.Text(), " "):
			if len(groups) == 0 || len(groups[len(groups)-1].Icons) == 0 {
				return nil, fmt.Errorf("line %d: a row of pixels needs an icon above it", n)
			}
			g := &groups[len(groups)-1]
			ic := &g.Icons[len(g.Icons)-1]
			if len(line) != pixmap.Size || len(ic.Rows) >= pixmap.Size {
				return nil, fmt.Errorf("line %d: an override is %d rows of %d characters", n, pixmap.Size, pixmap.Size)
			}
			ic.Rows = append(ic.Rows, line)
		case line == "" || strings.HasPrefix(line, "#"):
		default:
			if len(groups) == 0 {
				return nil, fmt.Errorf("line %d: %q is outside any [Group]", n, line)
			}
			fields := strings.Fields(line)
			if seen[fields[0]] {
				return nil, fmt.Errorf("line %d: %s is listed twice", n, fields[0])
			}
			seen[fields[0]] = true
			g := &groups[len(groups)-1]
			g.Icons = append(g.Icons, curatedIcon{Name: fields[0], Keywords: strings.Join(fields[1:], " ")})
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	for _, g := range groups {
		if len(g.Icons) == 0 {
			return nil, fmt.Errorf("group [%s] is empty", g.Name)
		}
		for _, ic := range g.Icons {
			if ic.Rows != nil && len(ic.Rows) != pixmap.Size {
				return nil, fmt.Errorf("%s: an override is %d rows, want %d", ic.Name, len(ic.Rows), pixmap.Size)
			}
		}
	}
	return groups, nil
}
